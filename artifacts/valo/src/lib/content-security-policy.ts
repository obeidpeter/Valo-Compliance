type Environment = Record<string, string | undefined>;
function authenticationOrigin(env: Environment): string | undefined {
  const key = env.VITE_CLERK_PUBLISHABLE_KEY || env.CLERK_PUBLISHABLE_KEY;
  if (!key) return undefined;
  const encoded = key.match(/^pk_(?:test|live)_([A-Za-z0-9+/=_-]+)$/)?.[1];
  if (!encoded) throw Error("INVALID_PUBLIC_AUTH_CONFIGURATION");
  let host: string;
  try {
    host = atob(encoded.replace(/-/g, "+").replace(/_/g, "/")).replace(/\$$/, "");
  } catch {
    throw Error("INVALID_PUBLIC_AUTH_CONFIGURATION");
  }
  if (!/^[a-z0-9]+(?:[a-z0-9.-]*[a-z0-9])?$/i.test(host) || !host.includes("."))
    throw Error("INVALID_PUBLIC_AUTH_CONFIGURATION");
  return "https://" + host.toLowerCase();
}

/** Server configuration only. A request Host/Forwarded header must never add a
 * CSP source. Per-response nonces are generated by Next middleware, not clients. */
export function contentSecurityPolicy(nonce: string, env: Environment = process.env): string {
  if (!/^[A-Za-z0-9+/=_-]{22,}$/.test(nonce)) throw Error("INVALID_CSP_NONCE");
  const deployed = Object.keys(env).some(
    (k) => (k === "REPLIT_DEPLOYMENT" || k.startsWith("REPLIT_DEPLOYMENT_")) && Boolean(env[k]?.length),
  );
  // The development server's own tooling: it evaluates code and reloads the page over a socket.
  const development = env.NODE_ENV === "development" && !deployed;
  // The development site, whether the development server or the compiled build the workspace serves
  // (`dev:compiled`), may be shown in the Replit workspace's preview. Nothing else of development
  // reaches the compiled build, and a deployment is never the development site.
  const developmentSite = (development || env.VALO_DEVELOPMENT_SITE === "compiled") && !deployed;
  const auth = authenticationOrigin(env),
    sources = auth ? [auth] : [];
  const directives: Record<string, string[]> = {
    "default-src": ["'self'"],
    "script-src": [
      "'self'",
      `'nonce-${nonce}'`,
      "'strict-dynamic'",
      ...sources,
      "https://challenges.cloudflare.com",
      "https://*.protect.clerk.com",
      ...(development ? ["'unsafe-eval'"] : []),
    ],
    // Fonts and styles come from this origin only (src/fonts.css); no visitor request goes to a font host.
    "style-src": ["'self'", "'unsafe-inline'"],
    "connect-src": [
      "'self'",
      ...sources,
      "https://challenges.cloudflare.com",
      "https://*.protect.clerk.com:*",
      "https://clerk-telemetry.com",
      "https://*.clerk-telemetry.com",
      ...(development ? ["ws:", "wss:"] : []),
    ],
    "img-src": ["'self'", "data:", "blob:", "https://img.clerk.com"],
    "font-src": ["'self'"],
    "frame-src": ["'self'", ...sources, "https://challenges.cloudflare.com", "https://*.protect.clerk.com"],
    "worker-src": ["'self'", "blob:"],
    "object-src": ["'none'"],
    "base-uri": ["'none'"],
    "form-action": ["'self'"],
    "frame-ancestors": developmentSite
      ? ["'self'", "https://replit.com", "https://*.replit.com"]
      : ["'none'"],
  };
  return (
    Object.entries(directives)
      .map(([name, values]) => `${name} ${values.join(" ")}`)
      .join("; ") + ";"
  );
}
