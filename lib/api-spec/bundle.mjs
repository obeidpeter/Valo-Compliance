/**
 * Builds openapi.yaml, the one contract file that code generation and the tests read, from the
 * files in src/. base.yaml holds the header and the responses every module shares. Each other file
 * is one API module: its paths, and the schemas only that module uses. shared.yaml holds the
 * schemas that more than one module, or a shared response, uses. Modules are joined in name order.
 *
 * The build fails on a line it cannot place, a path or schema defined twice, a reference to a schema
 * or response that does not exist, a schema nothing uses, and a schema in the wrong file. With
 * `--check` it writes nothing and fails when openapi.yaml is not what the sources build.
 *
 * Usage: node bundle.mjs [--check]
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const sourceFolder = new URL("./src/", import.meta.url);
const target = new URL("./openapi.yaml", import.meta.url);
const GENERATED = [
  "# Generated by bundle.mjs from the files in src/. Do not edit: change the module's file in src/,",
  "# then run `pnpm --filter @workspace/api-spec run codegen`.",
];
const SCHEMA_REF = /#\/components\/schemas\/([A-Za-z0-9_]+)/g;
const RESPONSE_REF = /#\/components\/responses\/([A-Za-z0-9_]+)/g;

const problems = [];
const problem = (file, message) => problems.push(`src/${file}: ${message}`);

/** A source file's lines, without the comment that opens it (it describes the file). */
function sourceLines(file) {
  const text = readFileSync(new URL(file, sourceFolder), "utf8");
  if (!text.endsWith("\n")) problem(file, "must end with a newline");
  const lines = text.replace(/\n$/, "").split("\n");
  let first = 0;
  while (first < lines.length && (lines[first].startsWith("#") || lines[first].trim() === "")) first++;
  return lines.slice(first);
}

/**
 * The entries of a section: each starts at two spaces of indentation with its key, and runs until
 * the next entry. `pattern` matches an entry's first line and captures its key. A comment or blank
 * line stays where it is, with the entry before it, or the first entry when none is before it.
 */
function entries(file, section, lines, pattern) {
  const found = [];
  let before = [];
  for (const line of lines) {
    const start = pattern.exec(line);
    if (start) {
      found.push({ key: start[1], lines: [...before, line] });
      before = [];
    } else if (/^\s*(#|$)/.test(line)) (found.at(-1)?.lines ?? before).push(line);
    else if (found.length > 0 && /^ {3,}\S/.test(line)) found.at(-1).lines.push(line);
    else problem(file, `cannot place this line in ${section}: ${line.slice(0, 80)}`);
  }
  if (before.length > 0) problem(file, `${section} holds comments but no entries`);
  return found;
}
const PATH_ENTRY = /^ {2}(\/[^\s:]*):(?:\s|$)/;
const SCHEMA_ENTRY = /^ {2}([A-Za-z0-9_]+):(?:\s|$)/;

/** A module or shared file: only top-level `paths:` and `schemas:` sections. */
function moduleFile(file) {
  const sections = { paths: [], schemas: [] };
  let current = null;
  for (const line of sourceLines(file)) {
    const top = /^(\S[^:]*):(.*)$/.exec(line);
    if (top && !line.startsWith("#")) {
      current = top[1];
      if (!(current in sections) || top[2].trim() !== "")
        problem(file, `only paths: and schemas: belong here: ${line}`);
      continue;
    }
    if (current === null) problem(file, `cannot place this line: ${line.slice(0, 80)}`);
    else if (current in sections) sections[current].push(line);
  }
  return {
    paths: entries(file, "paths", sections.paths, PATH_ENTRY),
    schemas: entries(file, "schemas", sections.schemas, SCHEMA_ENTRY),
  };
}

/** base.yaml: the header, then `components:` with only `responses:` under it. */
function baseFile() {
  const lines = sourceLines("base.yaml");
  const components = lines.indexOf("components:");
  if (components < 0 || lines[components + 1] !== "  responses:") {
    problem("base.yaml", "must end with components: and the shared responses: under it");
    return { header: lines, responses: [] };
  }
  const header = lines.slice(0, components);
  if (header.some((line) => /^(paths|webhooks):/.test(line)))
    problem("base.yaml", "paths belong in a module's file");
  const responses = entries(
    "base.yaml",
    "responses",
    lines.slice(components + 2).map((line) => line.replace(/^ {2}/, "")),
    SCHEMA_ENTRY,
  );
  return { header, responses };
}

const files = readdirSync(sourceFolder).filter((file) => file.endsWith(".yaml"));
for (const file of readdirSync(sourceFolder))
  if (!file.endsWith(".yaml")) problem(file, "only .yaml files belong in src/");
if (!files.includes("base.yaml")) problem("base.yaml", "is missing");
if (!files.includes("shared.yaml")) problem("shared.yaml", "is missing");
const base = files.includes("base.yaml") ? baseFile() : { header: [], responses: [] };
const shared = files.includes("shared.yaml") ? moduleFile("shared.yaml") : { paths: [], schemas: [] };
if (shared.paths.length > 0) problem("shared.yaml", "holds schemas only; paths belong in a module's file");
const modules = files
  .filter((file) => file !== "base.yaml" && file !== "shared.yaml")
  .sort()
  .map((file) => ({ file, name: file.replace(/\.yaml$/, ""), ...moduleFile(file) }));

// Each path and schema is defined once.
const pathFile = new Map();
const schemaFile = new Map();
const schemaText = new Map();
for (const { file, paths, schemas } of [...modules, { file: "shared.yaml", ...shared }]) {
  for (const path of paths) {
    if (pathFile.has(path.key)) problem(file, `${path.key} is also defined in src/${pathFile.get(path.key)}`);
    pathFile.set(path.key, file);
  }
  for (const schema of schemas) {
    if (schemaFile.has(schema.key))
      problem(file, `schema ${schema.key} is also defined in src/${schemaFile.get(schema.key)}`);
    schemaFile.set(schema.key, file);
    schemaText.set(schema.key, schema.lines.join("\n"));
  }
}
const responseText = new Map(base.responses.map((response) => [response.key, response.lines.join("\n")]));

// Every reference resolves.
const referenced = (text, pattern) => new Set([...text.matchAll(pattern)].map((match) => match[1]));
const checkReferences = (file, text) => {
  for (const name of referenced(text, SCHEMA_REF))
    if (!schemaText.has(name)) problem(file, `refers to schema ${name}, which no file defines`);
  for (const name of referenced(text, RESPONSE_REF))
    if (!responseText.has(name)) problem(file, `refers to response ${name}, which base.yaml does not define`);
};
checkReferences("base.yaml", [...responseText.values()].join("\n"));
for (const { file, paths, schemas } of [...modules, { file: "shared.yaml", ...shared }])
  checkReferences(file, [...paths, ...schemas].map((entry) => entry.lines.join("\n")).join("\n"));

/** Every schema the text reaches, directly or through other schemas. */
function reach(text) {
  const seen = new Set();
  const pending = [...referenced(text, SCHEMA_REF)];
  while (pending.length > 0) {
    const name = pending.pop();
    if (seen.has(name) || !schemaText.has(name)) continue;
    seen.add(name);
    pending.push(...referenced(schemaText.get(name), SCHEMA_REF));
  }
  return seen;
}

// A schema lives with its only user; one with several users, or a shared response's, is shared.
const users = new Map([...schemaText.keys()].map((name) => [name, new Set()]));
for (const name of reach([...responseText.values()].join("\n"))) users.get(name).add("a shared response");
for (const part of modules)
  for (const name of reach(part.paths.map((path) => path.lines.join("\n")).join("\n")))
    users.get(name).add(part.name);
for (const [name, file] of schemaFile) {
  const using = [...users.get(name)];
  const home = using.length === 1 && using[0] !== "a shared response" ? `${using[0]}.yaml` : "shared.yaml";
  if (using.length === 0) problem(file, `schema ${name} is used by no path or response`);
  else if (file !== home)
    problem(file, `schema ${name} is used by ${using.join(" and ")}: move it to src/${home}`);
}

if (problems.length > 0) {
  for (const message of problems) console.error(message);
  console.error(`The contract was not built: ${problems.length} problem(s) in lib/api-spec/src.`);
  process.exit(1);
}

const indent = (line) => (line === "" ? line : `  ${line}`);
const bundle = [
  ...GENERATED,
  ...base.header,
  "paths:",
  ...modules.flatMap((part) => part.paths.flatMap((path) => path.lines)),
  "components:",
  "  responses:",
  ...base.responses.flatMap((response) => response.lines.map(indent)),
  "  schemas:",
  ...[shared, ...modules].flatMap((file) => file.schemas.flatMap((schema) => schema.lines.map(indent))),
].join("\n");
const text = `${bundle}\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== text) {
    console.error(
      "lib/api-spec/openapi.yaml is not what lib/api-spec/src builds. Change the files in src/, then run `pnpm --filter @workspace/api-spec run codegen`.",
    );
    process.exit(1);
  }
} else writeFileSync(target, text);
