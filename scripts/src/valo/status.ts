import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { readiness } from "@workspace/valo-records";
import { CI_EVIDENCE_REGISTER, readCitations } from "./ci-evidence";

/** Generates docs/status.md from the requirement registers so status is never hand-written. */
const root = new URL("../../../", import.meta.url);
export const statusPath = fileURLToPath(new URL("docs/status.md", root));

type EvidenceRequirement = {
  id: string;
  release: string;
  implementation_status: string;
  acceptance_status?: string;
};
type EvidenceRegister = {
  date: string;
  status: string;
  requirements: EvidenceRequirement[];
  execution_register?: { generatedAt?: string; codeRevision?: string };
};

const yesNo = (value: boolean) => (value ? "yes" : "no");

export function renderStatus(): string {
  const state = readiness();
  const register = JSON.parse(
    readFileSync(fileURLToPath(new URL("docs/registers/implementation-evidence.json", root)), "utf8"),
  ) as EvidenceRegister;
  const byStatus = new Map<string, number>();
  for (const requirement of register.requirements)
    byStatus.set(
      requirement.implementation_status,
      (byStatus.get(requirement.implementation_status) ?? 0) + 1,
    );
  const unverified = register.requirements
    .filter((r) => r.implementation_status === "unverified")
    .map((r) => r.id);
  const citedOnly = register.requirements
    .filter((r) => r.implementation_status === "partial_development_with_ci_evidence")
    .map((r) => r.id);
  const citations = readCitations();
  const cited = new Map<string, { tests: Set<string>; jobs: Set<string> }>();
  for (const c of citations) {
    const entry = cited.get(c.requirement) ?? { tests: new Set<string>(), jobs: new Set<string>() };
    entry.tests.add(`${c.file}\0${c.test}`);
    entry.jobs.add(c.job);
    cited.set(c.requirement, entry);
  }
  const citedTests = new Set(citations.map((c) => `${c.file}\0${c.test}`)).size;
  const uncovered = unverified.filter((id) => !cited.has(id));
  const releaseOne = register.requirements.filter((r) => r.release === "R1").map((r) => r.id);
  const releaseOneUncited = releaseOne.filter((id) => !cited.has(id));
  const lines = [
    "# Valo status",
    "",
    "Generated by `pnpm --filter @workspace/scripts valo:status` from `docs/registers`.",
    "Do not edit by hand. A test fails if this file is out of date.",
    "",
    "## Release",
    "",
    "| Control | Value |",
    "| --- | --- |",
    `| R1 accepted | ${yesNo(state.r1Accepted)} |`,
    `| R2 unlocked | ${yesNo(state.r2Unlocked)} |`,
    `| Public launch enabled | ${yesNo(state.publicLaunchEnabled)} |`,
    `| Live payments enabled | ${yesNo(state.livePaymentsEnabled)} |`,
    `| Recurring billing enabled | ${yesNo(state.recurringBillingEnabled)} |`,
    `| Real customer data enabled | ${yesNo(state.confidentialCustomerDataEnabled)} |`,
    "",
    "## Requirements",
    "",
    `${state.receivedFormalRequirements} of ${state.expectedFormalRequirements} formal requirements are registered.`,
    `Implementation evidence register dated ${register.execution_register?.generatedAt ?? register.date}` +
      (register.execution_register?.codeRevision
        ? ` at \`${register.execution_register.codeRevision.slice(0, 7)}\`.`
        : "."),
    "",
    "| Implementation status | Requirements |",
    "| --- | ---: |",
    ...[...byStatus.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([status, count]) => `| ${status} | ${count} |`),
    "",
    `No evidence file, only tests cited in CI (decision 0010): ${citedOnly.join(", ") || "none"}.`,
    "",
    `No recorded evidence at all: ${unverified.join(", ") || "none"}.`,
    "",
    "## Tests cited as evidence",
    "",
    `\`${CI_EVIDENCE_REGISTER}\` holds ${citations.length} citations of ${citedTests} tests for ${cited.size} requirements (decision 0010).`,
    "A CI job fails when a test cited for it does not pass, and each run's `readiness-report` artifact lists every citation's result.",
    "A citation is partial evidence: it never accepts a requirement.",
    "",
    "| Requirement | Cited tests | CI jobs |",
    "| --- | ---: | --- |",
    ...[...cited.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([id, entry]) => `| ${id} | ${entry.tests.size} | ${[...entry.jobs].sort().join(", ")} |`),
    "",
    `Neither recorded implementation evidence nor a cited test: ${uncovered.join(", ") || "none"}.`,
    "",
    `No test is cited yet for ${releaseOneUncited.length} of the ${releaseOne.length} R1 requirements: ${releaseOneUncited.join(", ") || "none"}.`,
    "",
    "## Release gates",
    "",
    "| Gate | Planned window | Status |",
    "| --- | --- | --- |",
    ...state.gates.map((gate) => `| ${gate.gateId} | ${gate.plannedWindow} | ${gate.status} |`),
    "",
    "## Acceptance suites",
    "",
    "| Suite | Required cases | Executed | Accepted |",
    "| --- | ---: | ---: | --- |",
    ...state.suites.map(
      (suite) =>
        `| ${suite.id} | ${suite.requiredCases} | ${suite.executedCases} | ${yesNo(suite.accepted)} |`,
    ),
    "",
    "## User acceptance packages",
    "",
    "| Package | Title | Status |",
    "| --- | --- | --- |",
    ...state.uatPackages.map((uat) => `| ${uat.id} | ${uat.title} | ${uat.status} |`),
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(statusPath, renderStatus());
  process.stdout.write(`wrote ${statusPath}\n`);
}
